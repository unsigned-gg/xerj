//! Justfile Lowering Compiler for `org.projectfile.ci`.
//!
//! Generates clean, deterministic, dependency-tracked `Justfile` recipes
//! from a resolved CI intent DAG.
//!
//! # Invariants
//! - Zero-I/O: operates purely on memory strings and structured results.
//! - Deterministic output formatting and ordering.
//! - Preserves exact tool argument bindings and topological dependencies.

use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::collections::{BTreeMap, BTreeSet};

use super::ci::CiResolveResult;

/// Configuration options for Justfile code generation.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct JustTargetOptions {
    /// Shell interpreter definition (default: `["bash", "-euo", "pipefail", "-c"]`).
    pub shell: Vec<String>,
    /// Default recipe name to invoke on bare `just` (default: `"ci"`).
    pub default_target: String,
    /// Whether to emit file header and provenance comments.
    pub emit_preamble: bool,
}

impl Default for JustTargetOptions {
    fn default() -> Self {
        Self {
            shell: vec![
                "bash".to_string(),
                "-euo".to_string(),
                "pipefail".to_string(),
                "-c".to_string(),
            ],
            default_target: "ci".to_string(),
            emit_preamble: true,
        }
    }
}

/// Zero-I/O Justfile Lowering Compiler.
pub struct JustfileCompiler;

impl JustfileCompiler {
    /// Compiles a resolved CI execution plan into a standalone Justfile.
    #[must_use]
    pub fn compile(resolved: &CiResolveResult, options: &JustTargetOptions) -> String {
        Self::compile_with_runs(resolved, options, &BTreeMap::new())
    }

    fn compile_with_runs(
        resolved: &CiResolveResult,
        options: &JustTargetOptions,
        runs: &BTreeMap<String, String>,
    ) -> String {
        let mut out = String::new();

        if options.emit_preamble {
            out.push_str(
                "# Code generated by ls pf ci (LeanSpec Zero-I/O Lowering Engine). DO NOT EDIT.\n",
            );
            out.push_str("# Specification: https://projectfile.org/spec/v1\n\n");
        }

        // Set shell interpreter
        let shell_args: Vec<String> = options.shell.iter().map(|s| format!("\"{s}\"")).collect();
        out.push_str(&format!("set shell := [{}]\n\n", shell_args.join(", ")));

        // Map prerequisites for each tool from before-pairs
        let mut tool_deps: BTreeMap<&str, BTreeSet<&str>> = BTreeMap::new();
        for tool in &resolved.runs {
            tool_deps.entry(tool.as_str()).or_default();
        }

        for (first, second) in &resolved.before {
            if let Some(deps) = tool_deps.get_mut(second.as_str()) {
                deps.insert(first.as_str());
            }
        }

        // Default target recipe
        out.push_str(&format!("default: {}\n\n", options.default_target));

        // The CI aggregate target depends on all tools that are not prerequisites of other tools
        let all_prereqs: BTreeSet<&str> = tool_deps
            .values()
            .flat_map(|deps| deps.iter().copied())
            .collect();

        let terminal_tools: Vec<&str> = resolved
            .runs
            .iter()
            .map(String::as_str)
            .filter(|t| !all_prereqs.contains(*t))
            .collect();

        let ci_deps = if terminal_tools.is_empty() {
            resolved.runs.iter().map(String::as_str).collect::<Vec<_>>()
        } else {
            terminal_tools
        };

        out.push_str(&format!(
            "{}: {}\n\n",
            options.default_target,
            ci_deps.join(" ")
        ));

        // Generate recipes for each tool
        for tool in &resolved.runs {
            let deps = tool_deps.get(tool.as_str()).cloned().unwrap_or_default();
            let dep_str = if deps.is_empty() {
                String::new()
            } else {
                let mut v: Vec<&str> = deps.into_iter().collect();
                v.sort();
                format!(" {}", v.join(" "))
            };

            let count = resolved.counts.get(tool).copied().unwrap_or(1);
            out.push_str(&format!("# Tool target (timing class count: {count})\n"));
            out.push_str(&format!("{tool}:{dep_str}\n"));

            let cmd = runs.get(tool).map_or(tool.as_str(), String::as_str);
            if let Some(args) = resolved.args.get(tool) {
                out.push_str(&format!("    {cmd} {args}\n\n"));
            } else {
                out.push_str(&format!("    {cmd}\n\n"));
            }
        }

        out
    }

    /// Compiles a projectfile document AST and resolved DAG into a comprehensive Justfile with high-level nodes.
    #[must_use]
    pub fn compile_from_doc(
        doc: &Value,
        resolved: &CiResolveResult,
        options: &JustTargetOptions,
    ) -> String {
        let runs = super::xtask_target::XtaskCompiler::runs_from_doc(doc);
        let ci_section = doc
            .get("org")
            .and_then(|o| o.get("projectfile"))
            .and_then(|p| p.get("ci"))
            .or_else(|| doc.get("input"))
            .unwrap_or(doc);
        let input_val = ci_section.get("input").unwrap_or(ci_section);
        let nodes_obj = input_val.get("nodes").and_then(|n| n.as_object());

        let Some(nodes) = nodes_obj else {
            return Self::compile_with_runs(resolved, options, &runs);
        };

        let mut out = String::new();

        if options.emit_preamble {
            out.push_str(
                "# Code generated by ls pf ci (LeanSpec Zero-I/O Lowering Engine). DO NOT EDIT.\n",
            );
            out.push_str("# Specification: https://projectfile.org/spec/v1\n\n");
        }

        let shell_args: Vec<String> = options.shell.iter().map(|s| format!("\"{s}\"")).collect();
        out.push_str(&format!("set shell := [{}]\n\n", shell_args.join(", ")));

        out.push_str(&format!("default: {}\n\n", options.default_target));

        // High-level node recipes
        let mut goal_nodes = Vec::new();

        for (name, node_val) in nodes {
            let is_goal = node_val.get("goal").and_then(|g| g.as_bool()) == Some(true);
            if is_goal {
                goal_nodes.push(name.as_str());
            }

            let mut node_prereqs = Vec::new();
            let mut tool_invocations = Vec::new();

            for (dep, opt) in super::ci::normalize_needs_ordered(node_val.get("needs")) {
                if !opt.enabled {
                    continue;
                }

                if nodes.contains_key(&dep) {
                    node_prereqs.push(dep);
                } else {
                    let cmd = runs.get(&dep).map_or(dep.as_str(), String::as_str);
                    let arg = opt
                        .args
                        .as_deref()
                        .or_else(|| resolved.args.get(&dep).map(String::as_str))
                        .unwrap_or("");
                    if arg.is_empty() {
                        tool_invocations.push(cmd.to_string());
                    } else {
                        tool_invocations.push(format!("{cmd} {arg}"));
                    }
                }
            }

            let dep_str = if node_prereqs.is_empty() {
                String::new()
            } else {
                format!(" {}", node_prereqs.join(" "))
            };

            out.push_str(&format!("# Node: {name}\n"));
            out.push_str(&format!("{name}:{dep_str}\n"));
            for cmd in tool_invocations {
                out.push_str(&format!("    {cmd}\n"));
            }
            out.push('\n');
        }

        let ci_deps = if goal_nodes.is_empty() {
            nodes.keys().map(String::as_str).collect::<Vec<_>>()
        } else {
            goal_nodes
        };
        out.push_str(&format!(
            "{}: {}\n\n",
            options.default_target,
            ci_deps.join(" ")
        ));

        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    // SPEC-0003 requirement 15: gg.unsigned.ls.run replaces stage name with command line in Justfile recipes.
    #[test]
    fn run_section_gives_command_line_in_justfile() {
        let ci_doc = json!({
            "nodes": {
                "lint": {
                    "needs": {
                        "fmt": { "args": "--check" }
                    }
                },
                "verify": {
                    "goal": true,
                    "needs": ["lint", "test"]
                }
            }
        });
        let doc = json!({
            "gg": { "unsigned": { "ls": { "run": {
                "fmt": "cargo fmt --all",
                "test": "cargo test --workspace"
            } } } },
            "org": { "projectfile": { "ci": ci_doc } }
        });
        let resolved = super::super::ci::CiResolver::resolve_fixture(&ci_doc);
        let justfile =
            JustfileCompiler::compile_from_doc(&doc, &resolved, &JustTargetOptions::default());
        assert!(
            justfile.contains("    cargo fmt --all --check\n"),
            "fmt command line missing:\n{justfile}"
        );
        assert!(
            justfile.contains("    cargo test --workspace\n"),
            "test command line missing:\n{justfile}"
        );
    }
}

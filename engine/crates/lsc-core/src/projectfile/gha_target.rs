//! GitHub Actions Workflow Lowering Compiler for `org.projectfile.ci`.
//!
//! Lowers a resolved CI intent DAG into a deterministic GitHub Actions
//! workflow whose job delegates stage execution to `cargo xtask <goal>`
//! (SPEC-0003 requirement 16).
//!
//! # Invariants
//! - Zero-I/O: operates purely on in-memory strings and structured results.
//! - Deterministic output formatting and stage ordering comments.

use serde::{Deserialize, Serialize};
use serde_json::Value;

use super::ci::CiResolveResult;

/// Configuration options for GitHub Actions workflow code generation.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct GhaTargetOptions {
    /// Workflow display name (default: `"CI"`).
    pub workflow_name: String,
    /// Target `xtask` goal subcommand to invoke (default: `"xwork"`).
    pub default_target: String,
    /// GitHub Actions runner label (default: `"ubuntu-latest"`).
    pub runs_on: String,
    /// Job timeout in minutes (default: `20`).
    pub timeout_minutes: u32,
    /// Whether to emit file header and provenance comments.
    pub emit_preamble: bool,
}

impl Default for GhaTargetOptions {
    fn default() -> Self {
        Self {
            workflow_name: "CI".to_string(),
            default_target: "xwork".to_string(),
            runs_on: "ubuntu-latest".to_string(),
            timeout_minutes: 20,
            emit_preamble: true,
        }
    }
}

/// Zero-I/O GitHub Actions Lowering Compiler.
pub struct GhaCompiler;

impl GhaCompiler {
    /// Compiles a resolved CI execution plan into a GitHub Actions workflow YAML string.
    #[must_use]
    pub fn compile(resolved: &CiResolveResult, options: &GhaTargetOptions) -> String {
        Self::compile_with_goal(resolved, options, &options.default_target)
    }

    /// Compiles a projectfile document AST and resolved DAG into a GitHub Actions workflow YAML string.
    #[must_use]
    pub fn compile_from_doc(
        doc: &Value,
        resolved: &CiResolveResult,
        options: &GhaTargetOptions,
    ) -> String {
        let ci_section = doc
            .get("org")
            .and_then(|o| o.get("projectfile"))
            .and_then(|p| p.get("ci"))
            .or_else(|| doc.get("input"))
            .unwrap_or(doc);

        let goal = Self::resolve_goal_name(ci_section, &options.default_target);
        Self::compile_with_goal(resolved, options, &goal)
    }

    fn compile_with_goal(
        resolved: &CiResolveResult,
        options: &GhaTargetOptions,
        goal: &str,
    ) -> String {
        let mut out = String::new();
        let job_id = Self::sanitize_job_id(goal);

        if options.emit_preamble {
            out.push_str(
                "# Code generated by ls pf ci (LeanSpec Zero-I/O Lowering Engine). DO NOT EDIT.\n",
            );
            out.push_str("# Specification: https://projectfile.org/spec/v1\n");
            if !resolved.runs.is_empty() {
                out.push_str(&format!("# Stages: {}\n", resolved.runs.join(" -> ")));
            }
            out.push('\n');
        }

        out.push_str(&format!("name: {}\n\n", options.workflow_name));
        out.push_str("on:\n");
        out.push_str("  push:\n");
        out.push_str("    branches: [main]\n");
        out.push_str("  pull_request:\n");
        out.push_str("  workflow_dispatch:\n\n");
        out.push_str("permissions:\n");
        out.push_str("  contents: read\n\n");
        out.push_str("jobs:\n");
        out.push_str(&format!("  {job_id}:\n"));
        out.push_str(&format!("    name: {goal}\n"));
        out.push_str(&format!("    runs-on: {}\n", options.runs_on));
        out.push_str(&format!(
            "    timeout-minutes: {}\n",
            options.timeout_minutes
        ));
        out.push_str("    steps:\n");
        out.push_str("      - uses: actions/checkout@v4\n");
        out.push_str("      - uses: dtolnay/rust-toolchain@stable\n");
        out.push_str("        with:\n");
        out.push_str("          components: rustfmt, clippy\n");
        out.push_str(&format!("      - name: cargo xtask {goal}\n"));
        out.push_str(&format!("        run: cargo xtask {goal}\n"));

        out
    }

    fn resolve_goal_name(ci_section: &Value, configured: &str) -> String {
        if configured != "xwork" {
            return configured.to_string();
        }
        let input_val = ci_section.get("input").unwrap_or(ci_section);
        let Some(nodes) = input_val.get("nodes").and_then(Value::as_object) else {
            return configured.to_string();
        };
        if nodes.contains_key(configured) {
            return configured.to_string();
        }
        let flagged: Vec<&String> = nodes
            .iter()
            .filter(|(_, v)| v.get("goal").and_then(Value::as_bool) == Some(true))
            .map(|(k, _)| k)
            .collect();
        if flagged.len() == 1 {
            flagged[0].clone()
        } else {
            configured.to_string()
        }
    }

    fn sanitize_job_id(raw: &str) -> String {
        let s: String = raw
            .chars()
            .map(|c| {
                if c.is_ascii_alphanumeric() || c == '-' || c == '_' {
                    c
                } else {
                    '_'
                }
            })
            .collect();
        if s.is_empty() {
            "xwork".to_string()
        } else {
            s
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    // SPEC-0003 requirement 16: lowers resolved CI intent DAG into a GitHub Actions job that runs `cargo xtask <goal>`.
    #[test]
    fn lowers_dag_into_github_actions_job_running_cargo_xtask_goal() {
        let doc = json!({
            "nodes": {
                "lint": {
                    "needs": ["fmt", "clippy"]
                },
                "xwork": {
                    "goal": true,
                    "needs": ["lint", "test"]
                }
            }
        });
        let resolved = super::super::ci::CiResolver::resolve_fixture(&doc);
        let yaml = GhaCompiler::compile_from_doc(&doc, &resolved, &GhaTargetOptions::default());

        assert!(yaml.contains("# Stages: fmt -> clippy -> test"));
        assert!(yaml.contains("jobs:\n  xwork:\n    name: xwork\n"));
        assert!(yaml.contains("uses: actions/checkout@v4"));
        assert!(yaml.contains("run: cargo xtask xwork\n"));

        let parsed: serde_yaml::Value =
            serde_yaml::from_str(&yaml).expect("generated workflow must be valid YAML");
        let run_cmd = parsed["jobs"]["xwork"]["steps"][2]["run"]
            .as_str()
            .expect("step 2 run command");
        assert_eq!(run_cmd, "cargo xtask xwork");
    }

    #[test]
    fn custom_goal_updates_job_name_and_xtask_command() {
        let doc = json!({
            "nodes": {
                "install": {
                    "needs": ["rustup-components"]
                },
                "xwork": {
                    "goal": true,
                    "needs": ["install"]
                }
            }
        });
        let resolved = super::super::ci::CiResolver::resolve_goal(&doc, "install");
        let options = GhaTargetOptions {
            default_target: "install".to_string(),
            ..GhaTargetOptions::default()
        };
        let yaml = GhaCompiler::compile_from_doc(&doc, &resolved, &options);
        assert!(yaml.contains("  install:\n    name: install\n"));
        assert!(yaml.contains("run: cargo xtask install\n"));
    }
}
